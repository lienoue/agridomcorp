def normaliser(texte):
    """Enlève les accents, met en minuscule et nettoie"""
    if not texte:
        return ''
    return unicodedata.normalize('NFKD', texte).encode('ASCII', 'ignore').decode().lower().strip()


class Command(BaseCommand):
    help = "Met à jour les dates de plantation et de récolte pour toutes les cultures"

    def handle(self, *args, **kwargs):
        total_modifies = 0

        # On crée un dictionnaire normalisé pour la recherche
        ref_normalisee = {normaliser(k): v for k, v in DATES_REFERENCE.items()}

        # =========================================================
        # ÉTAPE 1 : FRUIT ET VEGETABLE (ont les champs plantation/recolte)
        # =========================================================
        self.stdout.write(self.style.WARNING("\n--- Mise à jour des Fruits et Légumes ---"))

        for modele in [Fruit, Vegetable]:
            for obj in modele.objects.all():
                nom_norm = normaliser(obj.nom)
                match_trouve = None

                # 1. Recherche exacte
                if nom_norm in ref_normalisee:
                    match_trouve = ref_normalisee[nom_norm]
                else:
                    # 2. Recherche par mots-clés
                    mots = nom_norm.split()
                    for mot in mots:
                        if len(mot) > 3:
                            if mot in ref_normalisee:
                                match_trouve = ref_normalisee[mot]
                                break
                            for cle, dates in ref_normalisee.items():
                                if mot in cle.split():
                                    match_trouve = dates
                                    break
                            if match_trouve:
                                break

                # 3. Mise à jour
                if match_trouve:
                    if obj.plantation != match_trouve['plantation'] or obj.recolte != match_trouve['recolte']:
                        obj.plantation = match_trouve['plantation']
                        obj.recolte = match_trouve['recolte']
                        obj.save()
                        total_modifies += 1
                        self.stdout.write(self.style.SUCCESS(f"✅ {modele.__name__} - {obj.nom}"))

        # =========================================================
        # ÉTAPE 2 : CULTURE (n'a pas plantation/recolte, on utilise conseils et saison_plantation)
        # =========================================================
        self.stdout.write(self.style.WARNING("\n--- Mise à jour des Cultures ---"))

        for obj in Culture.objects.all():
            nom_norm = normaliser(obj.nom)
            match_trouve = None

            # 1. Recherche exacte
            if nom_norm in ref_normalisee:
                match_trouve = ref_normalisee[nom_norm]
            else:
                # 2. Recherche par mots-clés
                mots = nom_norm.split()
                for mot in mots:
                    if len(mot) > 3:
                        if mot in ref_normalisee:
                            match_trouve = ref_normalisee[mot]
                            break
                        for cle, dates in ref_normalisee.items():
                            if mot in cle.split():
                                match_trouve = dates
                                break
                        if match_trouve:
                            break

            # 3. Mise à jour
            if match_trouve:
                texte_dates = f"Plantation : {match_trouve['plantation']} | Récolte : {match_trouve['recolte']}"

                # On vérifie si les dates ne sont pas déjà dans les conseils
                if texte_dates not in (obj.conseils or ''):
                    ancien_conseil = obj.conseils or ""
                    obj.conseils = f"{ancien_conseil}\n\n📅 {texte_dates}".strip()

                    # On met aussi à jour la saison de plantation si elle est vide
                    if not obj.saison_plantation:
                        obj.saison_plantation = match_trouve['plantation']

                    obj.save()
                    total_modifies += 1
                    self.stdout.write(self.style.SUCCESS(f"✅ Culture - {obj.nom}"))

        self.stdout.write(self.style.SUCCESS(f"\n🎉 Total : {total_modifies} cultures mises à jour."))